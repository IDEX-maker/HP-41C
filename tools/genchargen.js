// Build chargen.js (14-segment masks + text) from the Nonpareil 41CX calculator definition.
const fs = require('fs');
const src = fs.readFileSync(process.argv[2], 'utf8');
const re = /<char id="0x([0-9a-f]+)"\s+text="([^"]*)"\s*>([a-n.]{14})<\/char>/gi;
const seg = new Array(128).fill(0), txt = new Array(128).fill(' ');
let m, n = 0;
while ((m = re.exec(src))) {
  const id = parseInt(m[1], 16);
  let mask = 0;
  for (let i = 0; i < 14; i++) if (m[3][i] !== '.') mask |= 1 << i;
  seg[id] = mask; txt[id] = m[2].replace(/&amp;/g,'&').replace(/&lt;/g,'<').replace(/&gt;/g,'>').replace(/&quot;/g,'"').replace(/&apos;/g,"'");
  n++;
}
console.error('chars parsed:', n);
const out = `// Generated by tools/genchargen.js. Segment bit k = letter a..n (a=top, b=upper right, c=lower right,\n// d=bottom, e=lower left, f=upper left, g=left middle, h=right middle, i=top centre, j=bottom centre,\n// k=upper-right diagonal, l=upper-left diagonal, m=lower-right diagonal, n=lower-left diagonal).\n(function (root) {\n  const CHARGEN = { seg: ${JSON.stringify(seg)},\n    text: ${JSON.stringify(txt)} };\n  if (typeof module !== 'undefined' && module.exports) module.exports = CHARGEN; else root.CHARGEN = CHARGEN;\n})(typeof window !== 'undefined' ? window : globalThis);\n`;
fs.writeFileSync('chargen.js', out);
